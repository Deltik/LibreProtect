package net.deltik.mc.libreprotect.extension.migration;

/**
 * Asked between steps of a long migration whether it has to stop, such as
 * when the server is shutting down.
 */
@FunctionalInterface
interface StopCheck {

    /**
     * @throws MigrationException if the migration has to stop now
     */
    void check() throws MigrationException;

    /** Never stops */
    StopCheck NEVER = () -> {
    };
}
